-- PostgreSQL 16+. Execute somente em um banco de destino vazio.
-- As migrations MySQL históricas permanecem inalteradas.
BEGIN;
SET LOCAL TIME ZONE 'UTC';

CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL,
  senha_hash VARCHAR(255) NOT NULL,
  email_verificado SMALLINT NOT NULL DEFAULT 1 CHECK (email_verificado IN (0, 1)),
  logo_base64 TEXT NULL,
  logo_mime VARCHAR(50) NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE disciplinas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  usuario_id BIGINT NOT NULL,
  nome VARCHAR(120) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_usuario_disciplina UNIQUE (usuario_id, nome),
  CONSTRAINT fk_disciplinas_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE assuntos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  disciplina_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  nome VARCHAR(120) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_disciplina_assunto UNIQUE (disciplina_id, nome),
  CONSTRAINT fk_assuntos_disciplina
    FOREIGN KEY (disciplina_id) REFERENCES disciplinas(id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_assuntos_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE questoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  usuario_id BIGINT NOT NULL,
  disciplina_id BIGINT NULL,
  assunto_id BIGINT NULL,
  pergunta TEXT NOT NULL,
  imagem VARCHAR(255) NULL,
  alternativa_a TEXT NOT NULL,
  alternativa_b TEXT NOT NULL,
  alternativa_c TEXT NOT NULL,
  alternativa_d TEXT NOT NULL,
  correta VARCHAR(40) NOT NULL CHECK (correta IN ('A', 'B', 'C', 'D')),
  disciplina VARCHAR(120) NOT NULL,
  assunto VARCHAR(120) NOT NULL,
  dificuldade VARCHAR(40) NOT NULL CHECK (dificuldade IN ('Fácil', 'Média', 'Difícil')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_questoes_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
  CONSTRAINT fk_questoes_disciplina
    FOREIGN KEY (disciplina_id) REFERENCES disciplinas(id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  CONSTRAINT fk_questoes_assunto
    FOREIGN KEY (assunto_id) REFERENCES assuntos(id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
);

CREATE TABLE provas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  usuario_id BIGINT NOT NULL,
  escola VARCHAR(160) NOT NULL,
  professor VARCHAR(120) NOT NULL,
  disciplina VARCHAR(120) NOT NULL,
  assunto VARCHAR(120) NOT NULL,
  dificuldade VARCHAR(50) NOT NULL,
  quantidade_questoes INT NOT NULL,
  versao VARCHAR(10) NOT NULL DEFAULT 'A/B',
  data_prova DATE NULL,
  valor_avaliacao VARCHAR(30) NULL,
  dados_json TEXT NULL,
  data_geracao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_provas_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
    ON DELETE CASCADE
    ON UPDATE CASCADE,
  CONSTRAINT ck_provas_quantidade
    CHECK (quantidade_questoes IN (10, 15, 20, 25))
);

CREATE TABLE atividades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  usuario_id BIGINT NOT NULL,
  tipo VARCHAR(40) NOT NULL CHECK (tipo IN ('questao_criada', 'questao_editada', 'questao_excluida', 'prova_gerada', 'prova_excluida')),
  titulo VARCHAR(255) NOT NULL,
  descricao TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_atividades_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE TABLE recuperacao_senha (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  usuario_id BIGINT NOT NULL,
  token_hash VARCHAR(255) NOT NULL,
  expira_em TIMESTAMPTZ NOT NULL,
  usado BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_recuperacao_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
    ON DELETE CASCADE
    ON UPDATE CASCADE
);

CREATE INDEX idx_disciplinas_usuario ON disciplinas (usuario_id);

CREATE INDEX idx_assuntos_disciplina ON assuntos (disciplina_id);

CREATE INDEX idx_assuntos_usuario ON assuntos (usuario_id);

CREATE INDEX idx_questoes_usuario ON questoes (usuario_id);

CREATE INDEX idx_questoes_disciplina ON questoes (disciplina_id);

CREATE INDEX idx_questoes_assunto ON questoes (assunto_id);

CREATE INDEX idx_questoes_filtros ON questoes (usuario_id, disciplina, assunto, dificuldade);

CREATE INDEX idx_provas_usuario ON provas (usuario_id);

CREATE INDEX idx_provas_filtros ON provas (usuario_id, disciplina, assunto, dificuldade);

CREATE INDEX idx_atividades_usuario ON atividades (usuario_id, created_at DESC);

CREATE INDEX idx_recuperacao_usuario ON recuperacao_senha (usuario_id);

CREATE INDEX idx_recuperacao_token ON recuperacao_senha (token_hash);

CREATE TABLE verificacoes_email (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
  codigo_hash CHAR(64) NOT NULL,
  expira_em TIMESTAMPTZ NOT NULL,
  tentativas INTEGER NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
  enviado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_verificacoes_email_expira ON verificacoes_email (expira_em);
CREATE INDEX idx_questoes_usuario_created ON questoes (usuario_id, created_at DESC);
CREATE INDEX idx_provas_usuario_created ON provas (usuario_id, created_at DESC);
CREATE INDEX idx_questoes_usuario_disc_dif ON questoes (usuario_id, disciplina, dificuldade);
CREATE UNIQUE INDEX uk_usuarios_email_ci ON usuarios (LOWER(email));
CREATE UNIQUE INDEX uk_usuario_disciplina_ci ON disciplinas (usuario_id, LOWER(nome));
CREATE UNIQUE INDEX uk_disciplina_assunto_ci ON assuntos (disciplina_id, LOWER(nome));
CREATE INDEX ft_questoes_busca ON questoes USING GIN
  (to_tsvector('portuguese', pergunta || ' ' || disciplina || ' ' || assunto));

CREATE FUNCTION atualizar_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_usuarios_updated_at BEFORE UPDATE ON usuarios
  FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();
CREATE TRIGGER trg_disciplinas_updated_at BEFORE UPDATE ON disciplinas
  FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();
CREATE TRIGGER trg_assuntos_updated_at BEFORE UPDATE ON assuntos
  FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();
CREATE TRIGGER trg_questoes_updated_at BEFORE UPDATE ON questoes
  FOR EACH ROW EXECUTE FUNCTION atualizar_updated_at();

COMMIT;
